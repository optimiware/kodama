// Command gen embeds the workspace module's T020_001 migration, which lives at
// internal/workspace/migrations/T020_001_attempt_fk.sql (a path the execution
// task owns but cannot embed from a Go package of its own), into a constant in
// the execution PostgreSQL package. The SQL file stays the single authoritative
// copy; a test compares the constant byte for byte.
package main

import (
	"fmt"
	"os"
	"strings"
)

func main() {
	src, err := os.ReadFile("../../workspace/migrations/T020_001_attempt_fk.sql")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if strings.Contains(string(src), "`") {
		fmt.Fprintln(os.Stderr, "the migration must not contain backquotes")
		os.Exit(1)
	}
	out := "// Code generated by go generate; DO NOT EDIT.\n// Source: internal/workspace/migrations/T020_001_attempt_fk.sql\n\npackage postgres\n\n" +
		"// workspaceAttemptFKSQL is the exact content of T020_001_attempt_fk.sql.\nconst workspaceAttemptFKSQL = `" + string(src) + "`\n"
	if err := os.WriteFile("workspace_fk.gen.go", []byte(out), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
